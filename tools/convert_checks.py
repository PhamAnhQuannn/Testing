"""Convert source/assessment.json into mastery-check files and `kind: check` problems (T2.2a).

    uv run python tools/convert_checks.py            # or: make checks

Only items of the 40 MVP subtopics (content/index/subtopics.json) are converted; the rest are
skipped. Output (all generated: never edit by hand, re-run this tool instead):

* content/checks/<subtopic_id>.yaml   every converted item plus the author-added ones (below),
  in the shape of content/schemas/check.schema.json.
* content/problems/<subtopic_id>/<slug>/   one `kind: check` problem per `write_code` item.

Conventions
-----------
* Item ids are kept as they are in assessment.json (``Q023``, ``W185``, ...).
* Problem slug = ``check-`` + the lower-cased item id (``Q023`` -> ``check-q023``); the check item
  points at it with ``problem_id``. Problem id = slug = directory name. Status is ``validated``:
  the validator passes, no human review yet.
* ``minutes`` becomes the item's ``minutes`` and the problem's ``time_target_min`` (the time box).
* ``solution.py`` is the item's ``reference`` (re-formatted, helper classes the harness already
  provides are dropped). Test inputs come from the item's ``driver`` (its calls are recorded: the
  first is the sample, the others hidden tests) plus the hand-written inputs in
  tools/check_specs.py.
  ``expected`` is NEVER typed: tools/gen_hidden.py records it from solution.py. The driver's
  printed output must equal ``expected_output``, otherwise the conversion stops.
* io mode: ``function`` (linked lists and trees use the harness' ``list_node``/``tree_node``) or
  ``class_ops`` for class items. Items that cannot be graded as-is (e.g. ``Q080``, ``Q105``,
  ``W199``) are listed in SPECIAL in tools/check_specs.py, with the deviation in the statement.
* Problems are written next to each other and never deleted; the tool is idempotent (a second run
  rewrites identical bytes).

Author-added items (SPEC 3.4: the 9 subtopics without a level-2 write_code item)
------------------------------------------------------------------------------
This tool overwrites content/checks/*, so items that are NOT in assessment.json live in
``content/checks_extra/<subtopic_id>.yaml`` (same schema: ``subtopic_id`` + ``items``). The tool
appends them after the converted items of that subtopic. Use an id that cannot clash with
assessment.json: a letter other than Q/W plus digits, e.g. ``X001`` (an id clash is an error). The
problem of a ``write_code`` extra item is authored by hand under
content/problems/<subtopic_id>/<slug>/ (solution.py, tests/gen.py, hidden.jsonl via gen_hidden.py,
wrong/); the validator checks it like any other problem. Then run this tool so the merged
content/checks/<id>.yaml contains the item (the validator reports an unmerged extra item).
"""

import argparse
import ast
import contextlib
import copy
import io
import json
import re
import subprocess
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

from check_specs import EXTRA_INPUTS, SPECIAL
from common import CONTENT, ROOT, dump_jsonl, dump_yaml, load_json, load_yaml
from gen_hidden import generate_hidden
from run_problem import run_native

ASSESSMENT = ROOT / "source/assessment.json"
HEADER = (
    "# GENERATED by tools/convert_checks.py from source/assessment.json. Do not edit by hand.\n"
)
EXTRA_DIR = "checks_extra"
TIME_LIMIT_MS = 1000
RUN_LIMIT_MS = 10_000
SIMPLE_TYPES = {"int", "str", "bool", "float"}
HINTS = [
    "Đọc kỹ đề và ví dụ, xác định rõ đầu vào và đầu ra của `{target}` trước khi viết code.",
    "Thử tay với ví dụ đầu tiên, ghi lại từng bước, rồi chuyển các bước đó thành code.",
    "Kiểm tra các trường hợp biên (rỗng, một phần tử, giá trị lặp) trước khi nộp; nếu vẫn kẹt, "
    "xem lại bài học của mục này.",
]


class ConversionError(Exception):
    """An item that cannot be converted; the message names the item."""


@dataclass
class Plan:
    item: dict
    mode: str
    target: str
    code: str
    params: list[tuple[str, str]]
    returns: str | None
    calls: list
    extras: list
    note: str = ""
    names: list[str] = field(default_factory=list)


def slug_of(item_id: str) -> str:
    return f"check-{item_id.lower()}"


# --- reading the assessment ----------------------------------------------------------------------


def split_items(items: list[dict], subtopic_ids: set[str]) -> tuple[list[dict], list[dict]]:
    """(items of the MVP subtopics, the others), each in file order."""
    mvp = [i for i in items if i["subtopic_id"] in subtopic_ids]
    return mvp, [i for i in items if i["subtopic_id"] not in subtopic_ids]


def check_item(item: dict) -> dict:
    """The content/checks entry of one assessment item (SPEC 3.4)."""
    out = {
        "id": item["id"],
        "difficulty": item["difficulty"],
        "type": item["type"],
        "minutes": item["minutes"],
        "prompt_md": item["prompt"],
    }
    if item["type"] == "write_code":
        out["problem_id"] = slug_of(item["id"])
    elif item["type"] == "read_code":
        out["code"] = item["code"]
        out["expected_output"] = item["expected_output"]
        out["answer_md"] = item["answer"]
    else:
        out["answer_md"] = item["answer"]
    out["rubric_md"] = item["rubric"]
    return out


def load_extras(content: Path, subtopic_id: str) -> list[dict]:
    path = content / EXTRA_DIR / f"{subtopic_id}.yaml"
    if not path.is_file():
        return []
    data = load_yaml(path)
    if data.get("subtopic_id") != subtopic_id:
        raise ConversionError(f"{path.name}: subtopic_id must be {subtopic_id}")
    return data["items"]


def render_checks(subtopic_id: str, items: list[dict]) -> str:
    return HEADER + dump_yaml({"subtopic_id": subtopic_id, "items": items})


def build_checks(items: list[dict], content: Path) -> dict[str, list[dict]]:
    """subtopic id -> converted items followed by that subtopic's author-added items."""
    by_subtopic: dict[str, list[dict]] = {}
    for item in items:
        by_subtopic.setdefault(item["subtopic_id"], []).append(check_item(item))
    extra_dir = content / EXTRA_DIR
    extra_ids = sorted(p.stem for p in extra_dir.glob("*.yaml")) if extra_dir.is_dir() else []
    for subtopic_id in sorted({*by_subtopic, *extra_ids}):
        merged = by_subtopic.setdefault(subtopic_id, [])
        taken = {i["id"] for i in merged}
        for extra in load_extras(content, subtopic_id):
            if extra["id"] in taken:
                raise ConversionError(f"{subtopic_id}: extra item {extra['id']} clashes with an id")
            taken.add(extra["id"])
            merged.append(extra)
    return by_subtopic


# --- python source -------------------------------------------------------------------------------


def ruff_format(code: str, name: str) -> str:
    """The repo formatting (ruff, line length 100) so generated .py files pass `ruff format`."""
    proc = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", name, "-"],
        input=code,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=False,
    )
    if proc.returncode != 0:
        raise ConversionError(f"ruff format failed for {name}: {proc.stderr.strip()}")
    return proc.stdout


def reference_code(item: dict, keep: list[str] | None) -> str:
    """solution.py text: the reference, limited to the top-level names in `keep` when given."""
    tree = ast.parse(item["reference"])
    if keep is not None:
        tree.body = [
            node
            for node in tree.body
            if isinstance(node, ast.FunctionDef | ast.ClassDef) and node.name in keep
        ]
        missing = set(keep) - {node.name for node in tree.body}
        if missing:
            raise ConversionError(f"{item['id']}: reference has no {sorted(missing)}")
    return ruff_format(ast.unparse(tree) + "\n", "solution.py")


def check_driver_output(item: dict) -> None:
    """Reference + driver must print the item's expected_output (run in-process)."""
    namespace: dict = {"__name__": "__main__"}
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        exec(item["reference"], namespace)  # noqa: S102 - the repo's own upstream snapshot
        exec(item["driver"], namespace)  # noqa: S102
    printed = buffer.getvalue()
    if printed.rstrip() != item["expected_output"].rstrip():
        raise ConversionError(
            f"{item['id']}: driver printed {printed!r}, expected_output is "
            f"{item['expected_output']!r}"
        )


def record_calls(item: dict, entry: str) -> list[list]:
    """Replay the driver with `entry` wrapped, and return the arguments of each outer call."""
    namespace: dict = {"__name__": "__main__"}
    calls: list[list] = []
    depth = [0]
    with contextlib.redirect_stdout(io.StringIO()):
        exec(item["reference"], namespace)  # noqa: S102
        original = namespace[entry]

        def wrapper(*args, **kwargs):
            if depth[0] == 0:
                if kwargs:
                    raise ConversionError(f"{item['id']}: keyword call of {entry}")
                calls.append(copy.deepcopy(list(args)))
            depth[0] += 1
            try:
                return original(*args, **kwargs)
            finally:
                depth[0] -= 1

        namespace[entry] = wrapper
        exec(item["driver"], namespace)  # noqa: S102
    try:
        return json.loads(json.dumps(calls))
    except TypeError as error:
        raise ConversionError(
            f"{item['id']}: driver arguments are not plain data ({error}); add it to SPECIAL"
        ) from error


# --- planning one write_code item ----------------------------------------------------------------


def type_of(value) -> str:
    if value is None:
        return "none"
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, str):
        return "str"
    if isinstance(value, list):
        inner = {type_of(v) for v in value}
        return f"list[{inner.pop()}]" if len(inner) == 1 else ("list[any]" if inner else "list")
    return "any"


def merge_types(a: str, b: str) -> str:
    if a == b:
        return a
    if a == "list" and b.startswith("list"):
        return b
    if b == "list" and a.startswith("list"):
        return a
    return "any"


def merged_type(values: list) -> str:
    kinds = [type_of(v) for v in values]
    result = kinds[0]
    for kind in kinds[1:]:
        result = merge_types(result, kind)
    return result


def entry_of(item: dict) -> str:
    match = re.search(r"`([A-Za-z_]\w*)\(", item["prompt"])
    if not match:
        raise ConversionError(f"{item['id']}: no `name(` in the prompt; add it to SPECIAL")
    return match.group(1)


def plan_item(item: dict) -> Plan:
    special = SPECIAL.get(item["id"])
    if special is None:
        return plan_simple(item)
    if special.get("solution"):
        code = ruff_format(special["solution"], "solution.py")
    else:
        code = reference_code(item, special["keep"])
    if "tests" in special:  # class_ops: (driver-equivalent sequences, extra sequences)
        calls, extras = special["tests"]
        params: list[tuple[str, str]] = []
    else:
        calls, extras = special["calls"], special["extras"]
        params = special["params"]
    return Plan(
        item=item,
        mode=special.get("mode", "function"),
        target=special["target"],
        code=code,
        params=params,
        returns=special.get("returns"),
        calls=calls,
        extras=extras,
        note=special.get("note", ""),
    )


def plan_simple(item: dict) -> Plan:
    entry = entry_of(item)
    tree = ast.parse(item["reference"])
    func = next((n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == entry), None)
    if func is None:
        raise ConversionError(f"{item['id']}: reference has no top-level def {entry}")
    calls = record_calls(item, entry)
    if not calls:
        raise ConversionError(f"{item['id']}: the driver never calls {entry}")
    names = [a.arg for a in [*func.args.posonlyargs, *func.args.args]]
    width = max(len(c) for c in calls)
    if width > len(names):
        raise ConversionError(f"{item['id']}: more arguments than parameters")
    params = []
    for position in range(width):
        values = [c[position] for c in calls if len(c) > position]
        params.append((names[position], merged_type(values)))
    extras = EXTRA_INPUTS.get(item["id"])
    if extras is None:
        raise ConversionError(f"{item['id']}: no hand-written inputs in tools/check_specs.py")
    return Plan(
        item=item,
        mode="function",
        target=entry,
        code=reference_code(item, None),
        params=params,
        returns=None,
        calls=calls,
        extras=extras,
    )


# --- writing one check problem -------------------------------------------------------------------


def canonical(test_input) -> str:
    return json.dumps(test_input, sort_keys=True)


def as_test(value, mode: str) -> dict:
    return value if mode == "class_ops" else {"args": value}


def split_inputs(plan: Plan) -> tuple[dict, list[dict]]:
    """(sample input, hidden inputs): driver calls first, then the hand-written extras."""
    seen: set[str] = set()
    tests = []
    for source, value in [("driver", v) for v in plan.calls] + [("extra", v) for v in plan.extras]:
        test = as_test(value, plan.mode)
        if canonical(test) in seen:
            continue
        seen.add(canonical(test))
        tests.append((source, test))
    sample = tests[0][1]
    hidden = []
    edge_done = False
    for number, (source, test) in enumerate(tests[1:], start=1):
        tags = []
        if source == "extra" and not edge_done:
            tags, edge_done = ["edge"], True
        hidden.append({"id": f"h{number:02d}", **test, "tags": tags})
    if not edge_done and hidden:
        hidden[-1]["tags"] = ["edge"]
    return {"id": "s1", **sample}, hidden


def pretty(value) -> str:
    return repr(value)


def gen_py(slug: str, sample: dict, hidden: list[dict]) -> str:
    text = (
        f'"""Inputs of {slug}: generated by tools/convert_checks.py, do not edit by hand.\n\n'
        "`expected` is recorded from solution.py by tools/gen_hidden.py.\n"
        '"""\n\n'
        f"SAMPLE = {pretty(sample)}\n\n"
        f"HIDDEN = {pretty(hidden)}\n\n\n"
        "def sample_inputs():\n    return [SAMPLE]\n\n\n"
        "def hidden_inputs():\n    return HIDDEN\n\n\n"
        "def small_inputs(seed, n):\n    return []  # no brute.py: the cross-check is skipped\n"
    )
    return ruff_format(text, "tests/gen.py")


def starter_code(plan: Plan) -> str:
    if plan.mode == "class_ops":
        return f"class {plan.target}:\n    # TODO\n    pass\n"
    names = ", ".join(name for name, _ in plan.params)
    return f"def {plan.target}({names}):\n    # TODO\n    pass\n"


def signature(plan: Plan) -> str:
    if plan.mode == "class_ops":
        return f"class {plan.target}"
    return f"{plan.target}({', '.join(name for name, _ in plan.params)})"


def example_of(plan: Plan, sample: dict, expected) -> dict:
    if plan.mode == "class_ops":
        shown = f"ops = {pretty(sample['ops'])}, args = {pretty(sample['args'])}"
    else:
        shown = ", ".join(
            f"{name} = {pretty(value)}"
            for (name, _), value in zip(plan.params, sample["args"], strict=True)
        )
    return {
        "input": shown,
        "output": json.dumps(expected),
        "explain_vi": "Ví dụ đầu tiên của đề kiểm tra (driver của mục).",
    }


def complexity_of(item: dict) -> str:
    found = re.findall(r"O\([^)]*\)", item["prompt"])
    return " / ".join(dict.fromkeys(found)) if found else "n/a"


def build_problem(plan: Plan, io_def: dict, example: dict) -> dict:
    item = plan.item
    slug = slug_of(item["id"])
    statement = item["prompt"] + (f"\n\n{plan.note}" if plan.note else "")
    return {
        "id": slug,
        "subtopic_id": item["subtopic_id"],
        "secondary_subtopics": [],
        "kind": "check",
        "title": f"Check {item['id']}: {plan.target}",
        "title_vi": f"Kiểm tra {item['id']}: {plan.target}",
        "difficulty": "easy",
        "source": {"type": "original"},
        "statement_en_md": (
            f"Implement `{signature(plan)}` as described in the Vietnamese statement "
            f"(mastery check item {item['id']}, {item['minutes']}-minute time box)."
        ),
        "statement_vi_md": statement,
        "constraints": [],
        "examples": [example],
        "io": io_def,
        "starter": {"python": starter_code(plan)},
        "limits": {"time_ms": TIME_LIMIT_MS, "memory_mb": 256, "time_multiplier": {"pyodide": 3}},
        "time_target_min": item["minutes"],
        "hints": [h.format(target=plan.target) for h in HINTS],
        "solution": {
            "file": "solution.py",
            "approach_vi": "Xem code tham khảo trong solution.py (tạo từ `reference` của mục).",
            "complexity": complexity_of(item),
        },
        "tests": {
            "sample": "tests/sample.jsonl",
            "hidden": "tests/hidden.jsonl",
            "generator": "tests/gen.py",
        },
        "tags": ["check", item["id"].lower()],
        "status": "validated",
        "version": 1,
    }


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def io_for(plan: Plan, returns: str | None) -> dict:
    if plan.mode == "class_ops":
        return {"mode": "class_ops", "compare": "exact"}
    io_def = {
        "mode": "function",
        "entry": plan.target,
        "params": [{"name": name, "type": kind} for name, kind in plan.params],
    }
    if returns:
        io_def["returns"] = returns
    io_def["compare"] = "exact"
    return io_def


def write_problem(plan: Plan, content: Path) -> Path:
    item = plan.item
    directory = content / "problems" / item["subtopic_id"] / slug_of(item["id"])
    sample, hidden = split_inputs(plan)
    write(directory / "solution.py", plan.code)
    write(directory / "tests/gen.py", gen_py(slug_of(item["id"]), sample, hidden))
    # Record the reference's answers once to learn the return type and the statement example.
    probe = [dict(sample), *hidden]
    for test in probe:
        test.pop("tags", None)
    run = run_native(plan.code, io_for(plan, plan.returns), probe, RUN_LIMIT_MS)
    bad = [r for r in run["results"] if r["verdict"] != "AC"]
    if bad or len(run["results"]) != len(probe):
        raise ConversionError(f"{item['id']}: reference fails on its own inputs: {bad}")
    outputs = [r["got"] for r in run["results"]]
    returns = plan.returns or merged_type(outputs)
    problem = build_problem(plan, io_for(plan, returns), example_of(plan, sample, outputs[0]))
    write(directory / "problem.yaml", dump_yaml(problem))
    first = {**sample, "expected": outputs[0]}
    write(directory / "tests/sample.jsonl", dump_jsonl([first]))
    write(directory / "tests/hidden.jsonl", dump_jsonl(generate_hidden(directory)))
    return directory


# --- whole run -----------------------------------------------------------------------------------


def convert(assessment: Path, content: Path, only: set[str] | None = None) -> dict[str, int]:
    """Convert every in-scope item; returns counters for the summary line."""
    subtopics = load_json(content / "index/subtopics.json")["subtopics"]
    subtopic_ids = {s["id"] for s in subtopics}
    items = load_json(assessment)["items"]
    if only is not None:
        items = [i for i in items if i["id"] in only]
    mvp, skipped = split_items(items, subtopic_ids)
    code_items = [i for i in mvp if i["type"] == "write_code"]
    for item in code_items:
        check_driver_output(item)
    for subtopic_id, entries in build_checks(mvp, content).items():
        write(content / "checks" / f"{subtopic_id}.yaml", render_checks(subtopic_id, entries))
    for item in code_items:
        write_problem(plan_item(item), content)
    kinds = Counter(i["type"] for i in mvp)
    return {
        "items": len(items),
        "converted": len(mvp),
        "skipped": len(skipped),
        "skipped_write_code": sum(1 for i in skipped if i["type"] == "write_code"),
        "check_problems": len(code_items),
        "read_code": kinds["read_code"],
        "concept": kinds["concept"],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--assessment", type=Path, default=ASSESSMENT)
    parser.add_argument("--content", type=Path, default=CONTENT)
    parser.add_argument("--only", nargs="*", help="convert only these item ids (debugging)")
    args = parser.parse_args()
    try:
        counts = convert(args.assessment, args.content, set(args.only) if args.only else None)
    except ConversionError as error:
        print(f"ERROR {error}", file=sys.stderr)
        return 1
    print(
        f"{counts['converted']} of {counts['items']} items converted "
        f"({counts['check_problems']} write_code -> check problems, "
        f"{counts['read_code']} read_code, "
        f"{counts['concept']} concept); {counts['skipped']} skipped outside the MVP "
        f"({counts['skipped_write_code']} of them write_code)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
